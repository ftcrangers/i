create table if not exists public.rangers_ai_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  model_id text not null check (model_id in ('moiz','zum','nayah','fasheer','ranger')),
  created_at timestamptz not null default now()
);

create index if not exists rangers_ai_usage_user_created_idx
  on public.rangers_ai_usage (user_id, created_at desc);

alter table public.rangers_ai_usage enable row level security;
revoke all on public.rangers_ai_usage from anon, authenticated;
grant all on public.rangers_ai_usage to service_role;
